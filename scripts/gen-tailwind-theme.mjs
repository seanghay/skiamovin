#!/usr/bin/env node
// Generates packages/skiamovin/src/scene/tailwind-theme.ts from Tailwind CSS's default theme (MIT).
// Colors are converted from OKLCH to sRGB here, once, so every build uses the same values.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('tailwindcss/package.json'));
const css = readFileSync(join(pkgDir, 'theme.css'), 'utf8');
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;

const vars = new Map();
for (const m of css.matchAll(/^\s*--([\w-]+):\s*([^;]+);/gm)) vars.set(m[1], m[2].replace(/\s+/g, ' ').trim());

const px = (v) => {
  const m = /^(-?[\d.]+)(rem|px|em)?$/.exec(v.trim());
  if (!m) return null;
  return m[2] === 'rem' ? Number(m[1]) * 16 : Number(m[1]);
};

function oklchToHex(l, c, h, alpha = 1) {
  const L = l,
    a = c * Math.cos((h * Math.PI) / 180),
    b = c * Math.sin((h * Math.PI) / 180);
  const l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  const enc = (x) => {
    const v = Math.min(1, Math.max(0, x));
    return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
  };
  const hex = lin
    .map((x) =>
      Math.round(enc(x) * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('');
  return alpha < 1
    ? `#${hex}${Math.round(alpha * 255)
        .toString(16)
        .padStart(2, '0')}`
    : `#${hex}`;
}

function color(v) {
  const m = /^oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)$/.exec(v);
  if (m) return oklchToHex(Number(m[1]) / 100, Number(m[2]), Number(m[3]));
  if (/^#[0-9a-f]{3,8}$/i.test(v)) return v.length === 4 ? `#${[...v.slice(1)].map((c) => c + c).join('')}` : v;
  return null;
}

const colors = {};
for (const [k, v] of vars) {
  const m = /^color-([a-z]+)(?:-(\d+))?$/.exec(k);
  if (!m) continue;
  const c = color(v);
  if (!c) continue;
  if (m[2]) {
    colors[m[1]] ??= {};
    colors[m[1]][m[2]] = c;
  } else colors[m[1]] = c;
}

const fontSize = {};
for (const [k, v] of vars) {
  const m = /^text-([\w]+)$/.exec(k);
  if (!m || k.includes('--')) continue;
  const size = px(v);
  const lh = vars.get(`${k}--line-height`);
  const ratio = lh ? /calc\(([\d.]+)\s*\/\s*([\d.]+)\)/.exec(lh) : null;
  fontSize[m[1]] = [size, ratio ? Number(ratio[1]) / Number(ratio[2]) : lh ? Number(lh) : 1.5];
}

const pick = (prefix, conv) => {
  const out = {};
  for (const [k, v] of vars) {
    const m = new RegExp(`^${prefix}-([\\w.]+)$`).exec(k);
    if (m) {
      const val = conv(v);
      if (val !== null && val !== undefined && !Number.isNaN(val)) out[m[1]] = val;
    }
  }
  return out;
};

function shadows(v) {
  const out = [];
  for (const part of v.split(/,(?![^(]*\))/)) {
    const m =
      /^\s*(inset\s+)?(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?(?:\s+(-?[\d.]+)(?:px)?)?\s+rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)\s*$/.exec(
        part,
      );
    if (!m) return null;
    out.push({
      offset: [Number(m[2]), Number(m[3])],
      blur: Number(m[4]),
      spread: Number(m[5] ?? 0),
      color: `rgba(${m[6]},${m[7]},${m[8]},${m[9]})`,
    });
  }
  return out;
}

const theme = {
  spacing: px(vars.get('spacing')),
  colors,
  fontSize,
  fontWeight: pick('font-weight', Number),
  tracking: pick('tracking', (v) => px(v)),
  leading: pick('leading', Number),
  radius: pick('radius', px),
  shadow: pick('shadow', shadows),
  blur: pick('blur', px),
};

const out = `// Generated by scripts/gen-tailwind-theme.mjs from Tailwind CSS ${version}. Do not edit.
// Tailwind CSS is MIT licensed: Copyright (c) Tailwind Labs, Inc.
// Lengths are in pixels (1rem = 16px); tracking is in em; colors are sRGB.
export const tailwindTheme = ${JSON.stringify(theme, null, 2)} as const;
`;
writeFileSync(join(root, 'packages/skiamovin/src/scene/tailwind-theme.ts'), out);
console.log(
  `tailwind theme ${version}: ${Object.keys(colors).length} colors, ${Object.keys(fontSize).length} font sizes`,
);
