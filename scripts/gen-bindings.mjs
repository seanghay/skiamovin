#!/usr/bin/env node
// Generates the Node (napi-rs) and WebAssembly (emscripten) bindings, plus the TypeScript binding table,
// from the public functions in crates/skiamovin-core/src/api/*.rs.
//
// Only functions whose parameter and return types are all "wire" types are exported:
//   params:  u32 i32 f32 f64 bool &str &[u8] &[f32] &[u32]
//   returns: () u32 i32 f32 f64 bool String Vec<u8> Vec<f32> Vec<u32> Vec<i32> Vec<f64>, optionally wrapped in R<...>
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(root, 'crates/skiamovin-core/src/api');

const PARAM_TYPES = new Set(['u32', 'i32', 'f32', 'f64', 'bool', '&str', '&[u8]', '&[f32]', '&[u32]']);
const RET_TYPES = new Set([
  '()',
  'u32',
  'i32',
  'f32',
  'f64',
  'bool',
  'String',
  'Vec<u8>',
  'Vec<f32>',
  'Vec<u32>',
  'Vec<i32>',
  'Vec<f64>',
]);

const functions = [];
const skipped = [];

for (const file of readdirSync(apiDir).sort()) {
  if (!file.endsWith('.rs') || file === 'mod.rs' || file === 'manual.rs') continue;
  const mod = file.slice(0, -3);
  const src = readFileSync(join(apiDir, file), 'utf8');
  // Top-level `pub fn` (column 0), signature may span lines until `{`.
  const re = /^pub fn (\w+)(<[^>]*>)?\(([\s\S]*?)\)\s*(?:->\s*([^{]+?))?\s*\{/gm;
  for (const m of src.matchAll(re)) {
    const [, name, generics, paramsRaw, retRaw] = m;
    const params = paramsRaw
      .split(',')
      .map((p) => p.trim())
      .filter(Boolean)
      .map((p) => {
        const i = p.indexOf(':');
        return {
          name: p
            .slice(0, i)
            .trim()
            .replace(/^mut\s+/, ''),
          type: p.slice(i + 1).trim(),
        };
      });
    let ret = (retRaw ?? '()').trim();
    let fallible = false;
    const rm = /^R<(.+)>$/.exec(ret);
    if (rm) {
      fallible = true;
      ret = rm[1].trim();
    }
    const ok = !generics && params.every((p) => PARAM_TYPES.has(p.type)) && RET_TYPES.has(ret);
    if (!ok) {
      skipped.push(`${mod}::${name}`);
      continue;
    }
    functions.push({ mod, name, params, ret, fallible });
  }
}

// ---------------------------------------------------------------------------------------------------------------
// napi (Node)
// ---------------------------------------------------------------------------------------------------------------
const napiParam = {
  u32: 'u32',
  i32: 'i32',
  f32: 'f64',
  f64: 'f64',
  bool: 'bool',
  '&str': 'String',
  '&[u8]': 'Uint8Array',
  '&[f32]': 'Float32Array',
  '&[u32]': 'Uint32Array',
};
const napiArg = (p) => {
  switch (p.type) {
    case 'f32':
      return `${p.name} as f32`;
    case '&str':
      return `&${p.name}`;
    case '&[u8]':
    case '&[f32]':
    case '&[u32]':
      return `&${p.name}`;
    default:
      return p.name;
  }
};
const napiRet = {
  '()': '()',
  u32: 'u32',
  i32: 'i32',
  f32: 'f64',
  f64: 'f64',
  bool: 'bool',
  String: 'String',
  'Vec<u8>': 'Uint8Array',
  'Vec<f32>': 'Float32Array',
  'Vec<u32>': 'Uint32Array',
  'Vec<i32>': 'Int32Array',
  'Vec<f64>': 'Float64Array',
};
const napiConv = (ret, expr) => {
  switch (ret) {
    case 'f32':
      return `(${expr}) as f64`;
    case 'Vec<u8>':
      return `Uint8Array::new(${expr})`;
    case 'Vec<f32>':
      return `Float32Array::new(${expr})`;
    case 'Vec<u32>':
      return `Uint32Array::new(${expr})`;
    case 'Vec<i32>':
      return `Int32Array::new(${expr})`;
    case 'Vec<f64>':
      return `Float64Array::new(${expr})`;
    default:
      return expr;
  }
};

let napi = `// @generated by scripts/gen-bindings.mjs — do not edit.
#![allow(clippy::all, unused_imports)]
use napi::bindgen_prelude::*;
use napi_derive::napi;
use skiamovin_core::api;

fn err(e: String) -> napi::Error {
    napi::Error::new(napi::Status::GenericFailure, e)
}
`;
for (const f of functions) {
  const params = f.params.map((p) => `${p.name}: ${napiParam[p.type]}`).join(', ');
  const call = `api::${f.mod}::${f.name}(${f.params.map(napiArg).join(', ')})`;
  const rt = napiRet[f.ret];
  if (f.fallible) {
    const body = f.ret === '()' ? `${call}.map_err(err)` : `${call}.map(|v| ${napiConv(f.ret, 'v')}).map_err(err)`;
    napi += `\n#[napi(js_name = "${f.name}")]\npub fn ${f.name}(${params}) -> napi::Result<${rt}> {\n    ${body}\n}\n`;
  } else {
    napi += `\n#[napi(js_name = "${f.name}")]\npub fn ${f.name}(${params}) -> ${rt} {\n    ${napiConv(f.ret, call)}\n}\n`;
  }
}
writeFileSync(join(root, 'crates/skiamovin-node/src/generated.rs'), napi);

// ---------------------------------------------------------------------------------------------------------------
// emscripten (WebAssembly)
// ---------------------------------------------------------------------------------------------------------------
const wasmParams = (p) => {
  switch (p.type) {
    case '&str':
    case '&[u8]':
      return `${p.name}_ptr: *const u8, ${p.name}_len: usize`;
    case '&[f32]':
      return `${p.name}_ptr: *const f32, ${p.name}_len: usize`;
    case '&[u32]':
      return `${p.name}_ptr: *const u32, ${p.name}_len: usize`;
    case 'bool':
      return `${p.name}: i32`;
    default:
      return `${p.name}: ${p.type}`;
  }
};
const wasmArg = (p) => {
  switch (p.type) {
    case '&str':
      return `unsafe { crate::rt::str_from(${p.name}_ptr, ${p.name}_len) }`;
    case '&[u8]':
    case '&[f32]':
    case '&[u32]':
      return `unsafe { crate::rt::slice_from(${p.name}_ptr, ${p.name}_len) }`;
    case 'bool':
      return `${p.name} != 0`;
    default:
      return p.name;
  }
};
const wasmRetType = {
  '()': '',
  u32: ' -> u32',
  i32: ' -> i32',
  f32: ' -> f32',
  f64: ' -> f64',
  bool: ' -> i32',
  String: ' -> *const u8',
  'Vec<u8>': ' -> *const u8',
  'Vec<f32>': ' -> *const u8',
  'Vec<u32>': ' -> *const u8',
  'Vec<i32>': ' -> *const u8',
  'Vec<f64>': ' -> *const u8',
};
const wasmOk = (ret, v) => {
  switch (ret) {
    case '()':
      return `{ let _ = ${v}; }`;
    case 'bool':
      return `(${v}) as i32`;
    case 'String':
      return `crate::rt::ret_bytes(${v}.into_bytes())`;
    case 'Vec<u8>':
    case 'Vec<f32>':
    case 'Vec<u32>':
    case 'Vec<i32>':
    case 'Vec<f64>':
      return `crate::rt::ret_vec(${v})`;
    default:
      return v;
  }
};
const wasmDefault = {
  '()': '()',
  u32: '0',
  i32: '0',
  f32: '0.0',
  f64: '0.0',
  bool: '0',
  String: 'std::ptr::null()',
  'Vec<u8>': 'std::ptr::null()',
  'Vec<f32>': 'std::ptr::null()',
  'Vec<u32>': 'std::ptr::null()',
  'Vec<i32>': 'std::ptr::null()',
  'Vec<f64>': 'std::ptr::null()',
};

let wasm = `// @generated by scripts/gen-bindings.mjs — do not edit.
#![allow(clippy::all, unused_unsafe, unused_braces)]
use skiamovin_core::api;
`;
const exportNames = [];
for (const f of functions) {
  const params = f.params.map(wasmParams).join(', ');
  const call = `api::${f.mod}::${f.name}(${f.params.map(wasmArg).join(', ')})`;
  const body = f.fallible
    ? `match ${call} {\n        Ok(v) => ${wasmOk(f.ret, 'v')},\n        Err(e) => { crate::rt::set_error(e); ${wasmDefault[f.ret]} }\n    }`
    : wasmOk(f.ret, call);
  wasm += `\n#[no_mangle]\npub extern "C" fn skm_${f.name}(${params})${wasmRetType[f.ret]} {\n    ${body}\n}\n`;
  exportNames.push(`_skm_${f.name}`);
}
writeFileSync(join(root, 'crates/skiamovin-wasm/src/generated.rs'), wasm);
writeFileSync(join(root, 'crates/skiamovin-wasm/exports.txt'), `${exportNames.join('\n')}\n`);

// ---------------------------------------------------------------------------------------------------------------
// TypeScript: binding interface + signature table for the WASM marshaller
// ---------------------------------------------------------------------------------------------------------------
const tsParam = {
  u32: 'number',
  i32: 'number',
  f32: 'number',
  f64: 'number',
  bool: 'boolean',
  '&str': 'string',
  '&[u8]': 'Uint8Array',
  '&[f32]': 'Float32Array',
  '&[u32]': 'Uint32Array',
};
const tsRet = {
  '()': 'void',
  u32: 'number',
  i32: 'number',
  f32: 'number',
  f64: 'number',
  bool: 'boolean',
  String: 'string',
  'Vec<u8>': 'Uint8Array',
  'Vec<f32>': 'Float32Array',
  'Vec<u32>': 'Uint32Array',
  'Vec<i32>': 'Int32Array',
  'Vec<f64>': 'Float64Array',
};
const sigParam = {
  u32: 'u',
  i32: 'i',
  f32: 'f',
  f64: 'd',
  bool: 'b',
  '&str': 's',
  '&[u8]': 'B',
  '&[f32]': 'F',
  '&[u32]': 'U',
};
const sigRet = {
  '()': 'v',
  u32: 'u',
  i32: 'i',
  f32: 'f',
  f64: 'd',
  bool: 'b',
  String: 's',
  'Vec<u8>': 'B',
  'Vec<f32>': 'F',
  'Vec<u32>': 'U',
  'Vec<i32>': 'I',
  'Vec<f64>': 'D',
};

let ts = `// @generated by scripts/gen-bindings.mjs — do not edit.
/* eslint-disable */

/** Low-level binding surface shared by the native addon and the WebAssembly module. */
export interface GeneratedBinding {
`;
for (const f of functions) {
  ts += `  ${f.name}(${f.params.map((p) => `${p.name}: ${tsParam[p.type]}`).join(', ')}): ${tsRet[f.ret]};\n`;
}
ts += `}

/**
 * Signatures for the WebAssembly marshaller: "<params>:<return>" using
 * u=u32 i=i32 f=f32 d=f64 b=bool s=string B=bytes F=float32[] U=uint32[] I=int32[] D=float64[] v=void.
 */
export const SIGNATURES: Record<string, string> = {
`;
for (const f of functions) {
  ts += `  ${f.name}: '${f.params.map((p) => sigParam[p.type]).join('')}:${sigRet[f.ret]}',\n`;
}
ts += `};
`;
writeFileSync(join(root, 'packages/skiamovin/src/native/generated.ts'), ts);

console.log(`generated ${functions.length} functions; skipped ${skipped.length} helpers`);
if (process.argv.includes('--verbose')) console.log('skipped:', skipped.join(', '));
